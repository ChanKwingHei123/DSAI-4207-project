def resolve_gold_doc_ids(record):
    """Resolve the source paragraph so it can be excluded from retrieval."""
    question_id = record.get(
        "question_id",
        record.get("id", record.get("qid"))
    )

    # Preferred route: original SQuAD question ID.
    if question_id is not None:
        doc_id = question_id_to_doc_id.get(str(question_id))
        if doc_id:
            return {doc_id}

    # Support records that already contain corpus paragraph IDs.
    explicit_ids = record.get("gold_doc_ids", record.get("gold_doc_id"))
    if explicit_ids is not None:
        if isinstance(explicit_ids, str):
            explicit_ids = [explicit_ids]

        known_ids = set(corpus_df["doc_id"])
        resolved_ids = {str(x) for x in explicit_ids if str(x) in known_ids}
        if resolved_ids:
            return resolved_ids

    # Support records containing the original gold context.
    for key in ("gold_context", "context", "gold_text", "gold_passage"):
        context = record.get(key)
        if context:
            doc_id = text_to_doc_id.get(normalize_paragraph(context))
            if doc_id:
                return {doc_id}

    raise ValueError(
        f"Could not resolve the gold paragraph for question ID "
        f"{question_id!r}. Preserve the SQuAD question ID in the JSONL, "
        "or provide a gold paragraph ID or full gold context."
    )


def retrieve_hard_negatives(question, gold_doc_ids, top_k=TOP_K):
    """Return the top-k highest-similarity paragraphs, excluding gold."""
    query_embedding = embed_model.encode(
        [question],
        convert_to_numpy=True,
    ).astype("float32")
    query_embedding = np.ascontiguousarray(query_embedding)
    faiss.normalize_L2(query_embedding)

    # Search the full index, then filter gold paragraphs.
    scores, indices = faiss_index.search(
        query_embedding,
        faiss_index.ntotal,
    )

    negatives = []
    for score, idx in zip(scores[0], indices[0]):
        if idx < 0:
            continue

        row = corpus_df.iloc[int(idx)]
        if row["doc_id"] in gold_doc_ids:
            continue

        negatives.append({
            "doc_id": row["doc_id"],
            "text": row["text"],
            "score": float(score),
        })

        if len(negatives) == top_k:
            break

    if len(negatives) < top_k:
        raise ValueError(
            f"Only found {len(negatives)} non-gold paragraphs; "
            f"expected {top_k}."
        )

    return negatives


