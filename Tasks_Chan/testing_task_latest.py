# Set random seed for 10,000 paired bootstrap resamples
np.random.seed(42)
BOOTSTRAP_RESAMPLES = 10000

def run_paired_bootstrap(control_scores, treatment_scores):
    """
    Executes a non-parametric paired bootstrap to compute the mean difference
    and its corresponding 95% Confidence Interval (CI).
    """
    control = np.array(control_scores)
    treatment = np.array(treatment_scores)
    delta = treatment - control

    # Generate bootstrap distributions over the paired differences
    boot_indices = np.random.choice(len(delta), size=(BOOTSTRAP_RESAMPLES, len(delta)), replace=True)
    boot_means = delta[boot_indices].mean(axis=1)

    low_ci = np.percentile(boot_means, 2.5)
    high_ci = np.percentile(boot_means, 97.5)
    mean_diff = delta.mean()

    # Calculate a two-tailed p-value from the bootstrap distribution
    p_val = 2 * min((boot_means >= 0).mean(), (boot_means <= 0).mean())
    if p_val == 0:
        p_val = 1.0 / BOOTSTRAP_RESAMPLES # Precision limit guardrail

    return mean_diff, low_ci, high_ci, p_val

def apply_holm_bonferroni(p_values):
    """
    Applies multi-hypothesis step-down corrections to control familywise error bounds.
    """
    sorted_indices = np.argsort(p_values)
    m = len(p_values)
    adjusted_p = np.zeros(m)

    current_max = 0
    for rank, idx in enumerate(sorted_indices):
        raw_p = p_values[idx]
        # Holm correction formula: p_adj = raw_p * (m - rank)
        adj_p = min(raw_p * (m - rank), 1.0)
        current_max = max(current_max, adj_p)
        adjusted_p[idx] = current_max

    return adjusted_p

