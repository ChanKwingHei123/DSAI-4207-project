# Fast SQuAD normalization: build these once, not once per character.
_PUNCT_TRANSLATION = str.maketrans("", "", string.punctuation)
_ARTICLE_PATTERN = re.compile(r"\b(a|an|the)\b")
_COMPLIANCE_PATTERN = re.compile(r"^[\w\s\-\,\.$$$$]+$")


class SQuADMetricsEngine:
    """SQuAD-style token F1 and normalization."""

    @staticmethod
    def normalize_text(text):
        text = str(text or "").lower()
        text = text.translate(_PUNCT_TRANSLATION)
        text = _ARTICLE_PATTERN.sub(" ", text)
        return " ".join(text.split())

    @classmethod
    def calculate_f1(cls, prediction, ground_truth):
        pred_tokens = cls.normalize_text(prediction).split()
        gt_tokens = cls.normalize_text(ground_truth).split()

        # SQuAD convention: both empty strings score 1; only one empty scores 0.
        if not pred_tokens and not gt_tokens:
            return 1.0
        if not pred_tokens or not gt_tokens:
            return 0.0

        common = Counter(pred_tokens) & Counter(gt_tokens)
        num_same = sum(common.values())
        if num_same == 0:
            return 0.0

        precision = num_same / len(pred_tokens)
        recall = num_same / len(gt_tokens)
        return 2 * precision * recall / (precision + recall)


