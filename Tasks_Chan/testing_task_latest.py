def _block6_normalize_for_leak_check(text):
    text = str(text or "").lower()
    text = re.sub(r"\b(a|an|the)\b", " ", text)
    text = "".join(ch for ch in text if ch not in set("!\"#$%&'()*+,-./:;<=>?@[\$$^_`{|}~"))
