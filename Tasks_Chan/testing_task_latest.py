def compile_master_prompt_matrix(
    main_split_path,
    corpus_df,
    output_manifest_path,
    top_k=16,
):
    """
    Compile the prompt matrix.

    Hard negatives:
      - retrieved by FAISS similarity;
      - exclude the gold paragraph and normalized answer leaks.

    Random controls:
      - exclude the gold paragraph and gold article;
      - exclude normalized answer leaks;
      - match each random rank to the corresponding hard-negative length;
      - try ±20% first, then ±35% if necessary;
      - do not reuse random paragraphs within a question.
    """
    if "faiss_index" not in globals() or "embed_model" not in globals():
        raise RuntimeError(
            "Run Block 2 first so `faiss_index` and `embed_model` exist."
        )

    if "DB_DIR" not in globals():
        raise RuntimeError("DB_DIR must be defined before running Block 6.")

    if not os.path.exists(main_split_path):
        raise FileNotFoundError(
            f"Main question split not found: {main_split_path}"
        )

    required_columns = {"doc_id", "text", "source_article_idx"}
    missing_columns = required_columns - set(corpus_df.columns)
    if missing_columns:
        raise ValueError(
            f"corpus_df is missing required columns: {sorted(missing_columns)}"
        )

    if top_k < 8:
        raise ValueError("top_k must be at least 8.")

    questions_pool = _block6_load_jsonl(main_split_path)
    if not questions_pool:
        raise ValueError(f"No questions found in {main_split_path}")

    seeds = [42, 1337, 2026]

    dosage_conditions = [
        {"name": "hard_n=1", "dose": 1, "type": "hard"},
        {"name": "hard_n=2", "dose": 2, "type": "hard"},
        {"name": "hard_n=4", "dose": 4, "type": "hard"},
        {"name": "hard_n=8", "dose": 8, "type": "hard"},
        {"name": "random_n=1", "dose": 1, "type": "random"},
        {"name": "random_n=2", "dose": 2, "type": "random"},
        {"name": "random_n=4", "dose": 4, "type": "random"},
        {"name": "random_n=8", "dose": 8, "type": "random"},
    ]

    # Cache corpus columns for faster iteration.
    corpus_texts = corpus_df["text"].astype(str).tolist()
    corpus_doc_ids = corpus_df["doc_id"].astype(str).tolist()
    corpus_article_ids = corpus_df["source_article_idx"].tolist()
    corpus_token_lengths = [len(text.split()) for text in corpus_texts]
    corpus_normalized_texts = [
        _block6_normalize_for_leak_check(text)
        for text in corpus_texts
    ]

    text_to_doc_id = {
        _block6_normalize_paragraph(text): doc_id
        for text, doc_id in zip(corpus_texts, corpus_doc_ids)
    }
    doc_id_to_index = {
        doc_id: idx for idx, doc_id in enumerate(corpus_doc_ids)
    }

    output_dir = os.path.dirname(output_manifest_path)
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)

    os.makedirs(DB_DIR, exist_ok=True)
    hard_candidates_path = os.path.join(
        DB_DIR, "main_candidates_hard.jsonl"
    )

    master_prompt_ledger = []

    with open(hard_candidates_path, "w", encoding="utf-8") as candidates_file:
        for item in questions_pool:
            question_id = str(
                item.get("question_id", item.get("id", item.get("qid", "")))
            )
            if not question_id:
                raise ValueError(f"Question record has no ID: {item}")

            query = item.get(
                "question_text",
                item.get("question", item.get("query")),
            )
            if not query:
                raise ValueError(
                    f"Question text is missing for ID {question_id}."
                )
            query = str(query)

            gold_answer = str(item.get("gold_answer", "") or "")
            gold_passage = _block6_normalize_paragraph(
                item.get("gold_context", item.get("context", ""))
            )
            if not gold_passage:
                raise ValueError(
                    f"Gold context is missing for question {question_id}."
                )

            gold_doc_id = text_to_doc_id.get(gold_passage)
            if gold_doc_id is None:
                raise ValueError(
                    f"Gold context for question {question_id} was not found "
                    "in corpus_df."
                )

            gold_corpus_idx = doc_id_to_index[gold_doc_id]
            gold_article_idx = corpus_article_ids[gold_corpus_idx]
            normalized_answer = _block6_normalize_for_leak_check(gold_answer)

            # -------------------------------------------------------------
            # Retrieve hard negatives from FAISS.
            # -------------------------------------------------------------
            query_embedding = embed_model.encode(
                [query],
                convert_to_numpy=True,
            ).astype("float32")
            query_embedding = np.ascontiguousarray(query_embedding)
            faiss.normalize_L2(query_embedding)

            scores, indices = faiss_index.search(
                query_embedding,
                faiss_index.ntotal,
            )

            hard_negatives = []
            seen_hard_doc_ids = set()

            for score, index in zip(scores[0], indices[0]):
                if index < 0:
                    continue

                corpus_idx = int(index)
                doc_id = corpus_doc_ids[corpus_idx]

                if doc_id == gold_doc_id:
                    continue

                text = corpus_texts[corpus_idx]
                text_norm = corpus_normalized_texts[corpus_idx]

                if normalized_answer and normalized_answer in text_norm:
                    continue

                if doc_id in seen_hard_doc_ids:
                    continue

                seen_hard_doc_ids.add(doc_id)
                hard_negatives.append({
                    "doc_id": doc_id,
                    "text": text,
                    "score": float(score),
                })

                if len(hard_negatives) == top_k:
                    break

            if len(hard_negatives) < top_k:
                raise ValueError(
                    f"Question {question_id}: found only "
                    f"{len(hard_negatives)} clean hard negatives; "
                    f"need {top_k}."
                )

            # Save hard-negative candidates for review.
            candidates_file.write(json.dumps({
                "question_id": question_id,
                "question": query,
                "gold_doc_id": gold_doc_id,
                "hard_negatives": hard_negatives,
            }, ensure_ascii=False) + "\n")

            # -------------------------------------------------------------
            # Build eligible random-control pool:
            # different article, not the gold paragraph, no answer leak.
            # -------------------------------------------------------------
            eligible_indices = []

            for corpus_idx, doc_id in enumerate(corpus_doc_ids):
                if doc_id == gold_doc_id:
                    continue

                if corpus_article_ids[corpus_idx] == gold_article_idx:
                    continue

                if (
                    normalized_answer
                    and normalized_answer in corpus_normalized_texts[corpus_idx]
                ):
                    continue

                eligible_indices.append(corpus_idx)

            # Deterministic candidate ordering for this question.
            stable_seed = int(
                hashlib.sha256(question_id.encode("utf-8")).hexdigest()[:8],
                16,
            )
            rng = random.Random(stable_seed)
            rng.shuffle(eligible_indices)

            # -------------------------------------------------------------
            # Match eight random passages by rank to hard-negative lengths.
            # Try ±20%; use ±35% only if no unused ±20% candidate exists.
            # -------------------------------------------------------------
            random_pool = []
            random_match_tolerances = []
            used_random_doc_ids = set()

            for rank_idx in range(8):
                target_len = len(hard_negatives[rank_idx]["text"].split())
                chosen_idx = None
                chosen_tolerance = None

                for tolerance in (0.20, 0.35):
                    low_bound = target_len * (1 - tolerance)
                    high_bound = target_len * (1 + tolerance)

                    for corpus_idx in eligible_indices:
                        candidate_doc_id = corpus_doc_ids[corpus_idx]

                        if candidate_doc_id in used_random_doc_ids:
                            continue

                        candidate_len = corpus_token_lengths[corpus_idx]
                        if low_bound <= candidate_len <= high_bound:
                            chosen_idx = corpus_idx
                            chosen_tolerance = tolerance
                            break

                    if chosen_idx is not None:
                        break

                if chosen_idx is None:
                    raise ValueError(
                        f"Question {question_id}: no unused, cross-article "
                        f"random negative within ±35% for rank {rank_idx + 1} "
                        f"(hard-negative length={target_len} tokens)."
                    )

                chosen_doc_id = corpus_doc_ids[chosen_idx]
                used_random_doc_ids.add(chosen_doc_id)
                random_pool.append(corpus_texts[chosen_idx])
                random_match_tolerances.append(chosen_tolerance)

            # -------------------------------------------------------------
            # Closed-book and gold-oracle controls.
            # -------------------------------------------------------------
            master_prompt_ledger.append({
                "question_id": question_id,
                "condition": "closed-book",
                "seed": 42,
                "gold_position_index": -1,
                "rendered_prompt": f"Question: {query}\nAnswer:",
                "gold_answer": gold_answer,
            })

            master_prompt_ledger.append({
                "question_id": question_id,
                "condition": "oracle_n=0",
                "seed": 42,
                "gold_position_index": 0,
                "rendered_prompt": (
                    "Instructions: Read the context array carefully. "
                    "Answer the Query based strictly on inputs.\n"
                    f"[Context 1]: {gold_passage}\n"
                    f"Query: {query}\nAnswer:"
                ),
                "gold_answer": gold_answer,
            })

            # -------------------------------------------------------------
            # Treatment conditions and seed variants.
            # -------------------------------------------------------------
            for condition in dosage_conditions:
                dose = condition["dose"]

                if condition["type"] == "hard":
                    distractors = [
                        candidate["text"]
                        for candidate in hard_negatives[:dose]
                    ]
                    tolerances_for_record = None
                else:
                    distractors = random_pool[:dose]
                    tolerances_for_record = random_match_tolerances[:dose]

                for seed in seeds:
                    contexts = [gold_passage] + distractors
                    random.Random(seed).shuffle(contexts)
                    gold_position = contexts.index(gold_passage)

                    prompt = (
                        "Instructions: Read the context array carefully. "
                        "Answer the Query based strictly on inputs.\n"
                    )
                    for position, context in enumerate(contexts, start=1):
                        prompt += f"[Context {position}]: {context}\n"
                    prompt += f"Query: {query}\nAnswer:"

                    master_prompt_ledger.append({
                        "question_id": question_id,
                        "condition": condition["name"],
                        "seed": seed,
                        "gold_position_index": gold_position,
                        "rendered_prompt": prompt,
                        "gold_answer": gold_answer,
                        "random_length_match_tolerances": tolerances_for_record,
                    })

    with open(output_manifest_path, "w", encoding="utf-8") as output_file:
        for record in master_prompt_ledger:
            output_file.write(
                json.dumps(record, ensure_ascii=False) + "\n"
            )

    print(f"Compiled prompt records: {len(master_prompt_ledger):,}")
    print(f"Hard-negative candidates saved to: {hard_candidates_path}")
    print(f"Prompt matrix saved to: {output_manifest_path}")

    return len(master_prompt_ledger)


